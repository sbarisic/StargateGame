"""Import separate ZPM props and shared convex collision (numpy, Pillow, scipy).

Body-centred meshes use the existing authored metres. The empty hub's authored
convex hull fills sockets/recesses; these are props, not socketing gameplay.
"""
import json
from pathlib import Path
import numpy as np
from scipy.spatial import ConvexHull
from import_test_inspection_assets import import_model, ROOT, OUT


def hull_source(name, record):
    if name == 'Hub':
        points = np.array([list(map(float, line.split()[1:])) for line in
            (ROOT/'assets_itch/custom_models/zpm_hub/zpm_hub_collision.obj').read_text().splitlines()
            if line.startswith('v ')])
        # OBJ and GLB share Y-up source coordinates. Centre the authored envelope.
        points -= (points.min(0) + points.max(0)) / 2
    else:
        descriptor = json.loads((OUT/'zpm.json').read_text())
        points = np.concatenate([np.frombuffer((OUT/p['mesh']).read_bytes()[8:], dtype='<f4').reshape(-1, 8)[:, :3]
                                 for p in descriptor['parts']])
    hull = ConvexHull(points)
    used = sorted(set(hull.simplices.ravel()))
    indices = {old: new for new, old in enumerate(used)}
    faces = [[indices[i] for i in face] for face in hull.simplices]
    edges = sorted({tuple(sorted((f[i], f[(i+1)%3]))) for f in faces for i in range(3)})
    def vector(p): return 'new(' + ', '.join(f'{v:.7f}f' for v in p) + ')'
    half = np.maximum(np.abs(record['min']), np.abs(record['max']))
    # Round outwards, so bounds also conservatively enclose source precision.
    half = np.ceil(half * 10000) / 10000
    return (f'    public static readonly Vector3 {name}Half = {vector(half)};\n'
        f'    public static readonly PropGeometry.Hull {name}Hull = new(\n'
        '        [' + ', '.join(vector(points[i]) for i in used) + '],\n'
        '        [' + ', '.join(f'({a}, {b})' for a,b in edges) + '],\n'
        '        [' + ', '.join(f'({a}, {b}, {c})' for a,b,c in faces) + ']);\n')


if __name__ == '__main__':
    records = []
    code = 'using System.Numerics;\nnamespace StargateGame.Shared;\n\n// Generated by tools/import_zpm_props.py; body-centred metres.\npublic static class ZpmAsset\n{\n'
    for name, model, source in [('Hub', 'zpm-hub', 'zpm_hub.glb'), ('Module', 'zpm', 'zpm_module.glb')]:
        record = import_model(model, ROOT/'assets_itch/custom_models/zpm_hub'/source, body_centred=True)
        records.append(record)
        code += hull_source(name, record)
    (ROOT/'src/StargateGame.Shared/ZpmAsset.cs').write_text(code+'}\n')
    (ROOT/'assets/testing/zpm-props.json').write_text(json.dumps(records, indent=2)+'\n')
    print(json.dumps(records, indent=2))
